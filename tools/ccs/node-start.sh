#!/bin/bash

# This script provisions one node of the Wazuh CCS environment.
# Usage: ./node-start.sh <node_name>
# node_name can be "ccs", "cluster_a" or "cluster_b".
#
# Every node runs a single-node Wazuh indexer cluster. cluster_a and cluster_b add a Wazuh server;
# ccs adds the Wazuh dashboard and connects to the other two as remote clusters.
#
# It runs as root and expects:
#   - ARTIFACT_URLS in the environment: the artifact list to download the packages from.
#   - ca/, manager-ca/ and credentials.env in /tmp/ccs, uploaded by the Vagrantfile.
#
# The packages resolve passwords and certificates on their own when installed, each under its own
# configuration directory. Before each package is installed, this script stages what the
# environment shares in that package's directory: the CA in <conf>/ca/, so every node of the
# environment issues its certificates from the same one, and the passwords the environment chose
# in <conf>/local.env. Any password missing there is generated by the package, and published in
# <conf>/export/credentials.env for the other components on the node.

set -euo pipefail

NODE="${1-}"

# Must match the Vagrantfile.
CCS_HOSTNAME="ccs"
CLUSTER_A_IP="192.168.56.11"
CLUSTER_B_IP="192.168.56.12"

case "${NODE}" in
    ccs)       PREFIX="ccs"; IP="192.168.56.10" ;;
    cluster_a) PREFIX="ca";  IP="${CLUSTER_A_IP}" ;;
    cluster_b) PREFIX="cb";  IP="${CLUSTER_B_IP}" ;;
    *)
        echo "Usage: $0 <node_name>"
        echo "node_name can be 'ccs', 'cluster_a' or 'cluster_b'."
        exit 1
        ;;
esac

if [ -z "${ARTIFACT_URLS-}" ]; then
    echo "ARTIFACT_URLS is not set" >&2
    exit 1
fi

UPLOADS="/tmp/ccs"
DOWNLOADS="/var/tmp/ccs"
INDEXER_CONF="/etc/wazuh-indexer"
INDEXER_CERTS="${INDEXER_CONF}/certs"
INDEXER_EXPORT="${INDEXER_CONF}/export/credentials.env"
# The server's configuration directory. The 5.0.0 RC 2 specification moves it to
# /etc/wazuh-manager; until the server package ships that, the previous location applies.
MANAGER_CONF="${WAZUH_MANAGER_CONF:-/etc/wazuh-manager}"
DASHBOARD_CONF="/etc/wazuh-dashboard"

case "$(uname -m)" in
    x86_64)  ARCH="x86_64" ;;
    aarch64) ARCH="aarch64" ;;
    *) echo "Unsupported architecture: $(uname -m)" >&2; exit 1 ;;
esac

# Prints the value of a key in a KEY=VALUE file. The file is parsed, never sourced.
credential() {
    awk -v key="$2" 'index($0, key "=") == 1 { value = substr($0, length(key) + 2) } END { print value }' \
        "$1" | sed -e "s/^'\(.*\)'$/\1/" -e 's/^"\(.*\)"$/\1/'
}

# stage_ca <conf> <ca dir on the host>: the CA the package issues its certificates from. The
# packages accept it only when the directory and the files are root's and closed to others; the
# package sets the group its service needs once installed. Whatever a previous run left is kept.
stage_ca() {
    local conf="$1" src="$2"
    install -d -m 0750 -o root -g root "${conf}" "${conf}/ca"
    if [ ! -f "${conf}/ca/root-ca.pem" ]; then
        install -m 0640 -o root -g root "${src}/root-ca.pem" "${conf}/ca/root-ca.pem"
        install -m 0400 -o root -g root "${src}/root-ca.key" "${conf}/ca/root-ca.key"
    fi
}

# stage_local_env <conf> <KEY>...: the passwords the environment chose, in the package's own
# local.env, for the keys that package reads. Keys credentials.env does not hold are left to the
# package to generate.
stage_local_env() {
    local conf="$1"; shift
    local key value
    install -d -m 0750 -o root -g root "${conf}"
    [ -f "${conf}/local.env" ] && return 0
    (
        umask 077
        : > "${conf}/local.env"
        for key in "$@"; do
            value=$(credential "${UPLOADS}/credentials.env" "${key}")
            [ -n "${value}" ] && printf '%s=%s\n' "${key}" "${value}" >> "${conf}/local.env"
        done
    )
    chmod 0600 "${conf}/local.env"
}

installed() {
    rpm -q "$1" > /dev/null
}

# Downloads a package from the artifact list. Usage: download <component>
download() {
    local key="wazuh_$1_${ARCH}_rpm"
    local url
    url=$(awk -v key="${key}:" '$1 == key { gsub(/"/, "", $2); print $2 }' "${DOWNLOADS}/artifact_urls.yaml")
    if [ -z "${url}" ]; then
        echo "${key} is not in ${ARTIFACT_URLS}" >&2
        exit 1
    fi
    echo "Downloading ${url}"
    curl -fsSL --retry 5 -o "${DOWNLOADS}/wazuh-$1.rpm" "${url}"
}

install_indexer() {
    download indexer
    stage_ca "${INDEXER_CONF}" "${UPLOADS}/ca"
    stage_local_env "${INDEXER_CONF}" WAZUH_INDEXER_ADMIN_PASSWORD WAZUH_INDEXER_KIBANASERVER_PASSWORD WAZUH_INDEXER_MANAGER_PASSWORD
    # The clusters reach each other on the private network with hostname verification enabled, so
    # the certificate names this host by its private address, and not by the provider's management
    # interface the indexer would also discover.
    printf 'WAZUH_INDEXER_CERT_SANS=DNS:%s,IP:%s\n' "$(hostname -s)" "${IP}" >> "${INDEXER_CONF}/local.env"
    dnf install -y "${DOWNLOADS}/wazuh-indexer.rpm"

    local config="${INDEXER_CONF}/opensearch.yml"
    sed -i "s/node-1/${PREFIX}-wazuh-indexer-1/g" "${config}"
    sed -i "s/^cluster\.name:.*$/cluster.name: \"${PREFIX}-cluster\"/" "${config}"
    # Listen on every interface, since the server and the dashboard connect through localhost, but
    # publish the private address, which is the one the CCS node connects to.
    echo "network.publish_host: \"${IP}\"" >> "${config}"

    if [ "${NODE}" != "ccs" ]; then
        # A remote cluster only accepts the CCS node if its certificate is listed as a node's. Both
        # are issued by the package with the same DN but for the CN, which is the host name.
        local node_dn ccs_dn
        node_dn=$(openssl x509 -in "${INDEXER_CERTS}/indexer.pem" -noout -subject -nameopt RFC2253 | sed 's/^subject= *//')
        ccs_dn=$(echo "${node_dn}" | sed "s/\(^\|,\)CN=[^,]*/\1CN=${CCS_HOSTNAME}/")
        sed -i "/^plugins\.security\.nodes_dn:/a - \"${ccs_dn}\"" "${config}"
    fi

    systemctl daemon-reload
    systemctl enable --now wazuh-indexer

    # Load the security configuration, with the passwords the package wrote in it, into the cluster.
    /usr/share/wazuh-indexer/bin/indexer-security-init.sh
}

install_manager() {
    download manager
    stage_ca "${MANAGER_CONF}" "${UPLOADS}/manager-ca"
    # The indexer password and CA are imported from the indexer's export/ on this node. The WUI
    # password is the environment's, so that the dashboard on the CCS node knows it.
    stage_local_env "${MANAGER_CONF}" WAZUH_MANAGER_API_PASSWORD WAZUH_MANAGER_WUI_PASSWORD
    dnf install -y "${DOWNLOADS}/wazuh-manager.rpm"

    systemctl daemon-reload
    systemctl enable --now wazuh-manager
}

install_dashboard() {
    download dashboard
    # The kibanaserver password and the indexer CA are imported from the indexer's export/ on this
    # node. The Server API password is the environment's, and the servers' CA is staged: both
    # remote servers issue their API certificates from it.
    stage_local_env "${DASHBOARD_CONF}" WAZUH_MANAGER_WUI_PASSWORD
    install -d -m 0750 -o root -g root "${DASHBOARD_CONF}/certs"
    install -m 0640 -o root -g root "${UPLOADS}/manager-ca/root-ca.pem" "${DASHBOARD_CONF}/certs/manager-ca.pem"
    dnf install -y "${DOWNLOADS}/wazuh-dashboard.rpm"

    local config="${DASHBOARD_CONF}/opensearch_dashboards.yml"
    # The account the dashboard authenticates to the servers with: the one the package's own
    # default host uses.
    local api_user
    api_user=$(awk '/^wazuh_core\.hosts:/ { hosts = 1 } hosts && $1 == "username:" { print $2; exit }' "${config}")
    api_user="${api_user:-wazuh-internal-client}"

    # Replace the default host, a server on this node, with the servers of both remote clusters,
    # each verified against the servers' CA.
    local hosts
    hosts=$(awk '/^wazuh_core\.hosts:/ { skip = 1; next } skip && /^[[:space:]]/ { next } { skip = 0; print }' "${config}")
    cat > "${config}" << EOF
${hosts}
wazuh_core.hosts:
  cluster-a:
    url: https://${CLUSTER_A_IP}
    port: 55000
    username: ${api_user}
    run_as: true
    ca: '${DASHBOARD_CONF}/certs/manager-ca.pem'
  cluster-b:
    url: https://${CLUSTER_B_IP}
    port: 55000
    username: ${api_user}
    run_as: true
    ca: '${DASHBOARD_CONF}/certs/manager-ca.pem'
EOF

    # Both servers were installed with the WAZUH_MANAGER_WUI_PASSWORD of the environment. The
    # keystore is root's; the package sets the group its service needs after every write.
    local password
    password=$(credential "${UPLOADS}/credentials.env" WAZUH_MANAGER_WUI_PASSWORD)
    dashboard_keystore remove wazuh_core.hosts.default.password > /dev/null 2>&1 || true
    for host in cluster-a cluster-b; do
        printf '%s' "${password}" | dashboard_keystore add --force --stdin "wazuh_core.hosts.${host}.password" > /dev/null
    done
    chown root:wazuh-dashboard "${DASHBOARD_CONF}/opensearch_dashboards.keystore"
    chmod 0640 "${DASHBOARD_CONF}/opensearch_dashboards.keystore"

    systemctl daemon-reload
    systemctl enable --now wazuh-dashboard
}

dashboard_keystore() {
    (cd / && env OSD_PATH_CONF="${DASHBOARD_CONF}" \
        /usr/share/wazuh-dashboard/bin/opensearch-dashboards-keystore --allow-root "$@")
}

# Authenticates with the admin certificate, so no password is needed.
configure_remote_clusters() {
    curl -fsS --cacert "${INDEXER_CERTS}/root-ca.pem" \
        --cert "${INDEXER_CERTS}/admin.pem" --key "${INDEXER_CERTS}/admin-key.pem" \
        -X PUT "https://localhost:9200/_cluster/settings" -H 'Content-Type: application/json' -d @- << EOF
{
    "persistent": {
        "cluster.remote": {
            "ca-wazuh-indexer-1": { "seeds": ["${CLUSTER_A_IP}:9300"] },
            "cb-wazuh-indexer-1": { "seeds": ["${CLUSTER_B_IP}:9300"] }
        }
    }
}
EOF
    echo
}

systemctl disable --now firewalld > /dev/null 2>&1 || true

mkdir -p "${DOWNLOADS}"
curl -fsSL --retry 5 -o "${DOWNLOADS}/artifact_urls.yaml" "${ARTIFACT_URLS}"

# A component already installed by a previous run is left as it is. Not written as
# `installed ... || install_...`: errexit is ignored inside a function called that way.
if ! installed wazuh-indexer; then
    install_indexer
fi
if [ "${NODE}" == "ccs" ]; then
    if ! installed wazuh-dashboard; then
        install_dashboard
    fi
    configure_remote_clusters
else
    if ! installed wazuh-manager; then
        install_manager
    fi
fi

rm -rf "${UPLOADS}" "${DOWNLOADS}"

echo "${NODE} is ready. The indexer passwords of this node are in ${INDEXER_EXPORT}."
if [ "${NODE}" != "ccs" ]; then
    echo "The Wazuh server passwords are in ${MANAGER_CONF}/export/credentials.env."
fi
